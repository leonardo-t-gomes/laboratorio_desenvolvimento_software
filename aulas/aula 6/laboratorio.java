    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {                                           
        int linha = tblPessoas.getSelectedRow();
        if (linha == -1){
            JOptionPane.showMessageDialog(
                    null,
                    "Selecoione uma pessoa na tabela.",
                    "Atenção",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(
                null,
                "Deseja realmente excluir esta pessoa",
                "confirmação",
                JOptionPane.YES_NO_OPTION
        );
        
        if (resposta == JOptionPane.YES_OPTION){
            listaPessoas.remove(linha);
            
            arquivo.gravaArquivo();
            
            DefaultTableModel tabela = (DefaultTableModel) tblPessoas.getModel();
            
            tabela.removeRow(linha);
            
            System.out.println("Pessoa Excluida");
        }
    }                                          

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {                                          
        int linha = tblPessoas.getSelectedRow();
        
        if (linha == -1){
            JOptionPane.showMessageDialog(
                    null,
                    "Selecione uma pessoa para editar"
            );
            return;
        }
        linhaEdicao = linha;
        Pessoa p = listaPessoas.get(linha);
        txtNome.setText(p.nome);
        if(p.sexo == 'M'){
           rdo_Masculino .setSelected(true);
        }else{
            rdo_Feminino .setSelected(true);
        }
        
        cnbIdioma.setSelectedItem(p.idioma);
    }                                         

