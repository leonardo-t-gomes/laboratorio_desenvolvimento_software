    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {                                          
    // 1. Validação do Nome
    if (txtNome.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Digite o nome!", "Alerta", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Validação do Sexo
    if (!rdo_Masculino.isSelected() && !rdo_Feminino.isSelected()) {
        JOptionPane.showMessageDialog(this, "Selecione um sexo!", "Alerta", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 3. Coleta dos dados dos componentes
    char sexoSelecionado = rdo_Masculino.isSelected() ? 'M' : 'F';
    boolean tecnologia = chkTecnologia.isSelected();
    boolean astronomia = chkAstronomia.isSelected();
    boolean esportes = chkEsporte.isSelected();
    String idioma = String.valueOf(cnbIdioma.getSelectedItem());

    // 4. Criação do objeto Pessoa
    Pessoa p = new Pessoa(
        txtNome.getText().trim(),
        sexoSelecionado,
        idioma,
        tecnologia,
        astronomia,
        esportes
    );

    DefaultTableModel tabela = (DefaultTableModel) tblPessoas.getModel();

    // 5. Verificação: inserção de nova pessoa ou edição
    if (linhaEdicao == -1) {
        listaPessoas.add(p);
        tabela.addRow(p.obterDados()); // Adiciona a nova linha direto na JTable
    } else {
        listaPessoas.set(linhaEdicao, p);
        
        // Atualiza a linha existente na tabela visualmente
        Object[] dados = p.obterDados();
        for (int col = 0; col < dados.length; col++) {
            tabela.setValueAt(dados[col], linhaEdicao, col);
        }
        linhaEdicao = -1; // Reseta o estado de edição
    }

    // 6. Gravação e atualização visual
    arquivo.gravaArquivo();
    txaPessoas.append(p.toString() + "\n");

    JOptionPane.showMessageDialog(this, "Dados salvos com sucesso!");
    limparCampos();
    }                                         

